package io.dagger.annotation.processor;

import io.dagger.module.info.EnumInfo;
import io.dagger.module.info.FieldInfo;
import io.dagger.module.info.FunctionInfo;
import io.dagger.module.info.ModuleInfo;
import io.dagger.module.info.ObjectInfo;
import io.dagger.module.info.ParameterInfo;
import java.util.ArrayList;
import java.util.List;

/**
 * Renders the module's Dang entrypoint: the {@link ModuleInfo} that {@code register()} sends to the
 * engine at run time, as static {@code types}, and a {@code call} that runs the generated {@code
 * Entrypoint} in {@code engine-call} mode, declaring the engine release the module's core is
 * generated for on the process it starts. Both backends must describe the same schema.
 */
final class DangEntrypointRenderer {

  static final String HEADER = "# This file has been generated by dagger-java-sdk. DO NOT EDIT.\n";

  static final String FUNCTION_ERROR_MARKER = "::dagger-function-error::";

  static final String RESULT_PATH = "/dagger/result.json";

  static final String CLIENT_VERSION_VARIABLE = "DAGGER_CLIENT_VERSION";

  private DangEntrypointRenderer() {}

  static String render(ModuleInfo moduleInfo, String moduleName, String clientVersion) {
    DaggerType.setKnownEnums(moduleInfo.enumInfos().keySet());

    List<String> defs = new ArrayList<>();
    for (ObjectInfo object : moduleInfo.objects()) {
      defs.add(renderObject(object, moduleName));
    }
    for (EnumInfo enumInfo : moduleInfo.enumInfos().values()) {
      defs.add(renderEnum(enumInfo));
    }

    StringBuilder b = new StringBuilder(HEADER);
    b.append("\ntype Entrypoint implements ModuleEntrypoint {\n");
    b.append(SOURCES);
    b.append("\n  pub types: [TypeDef!]! {\n    [\n");
    for (String def : defs) {
      b.append(Dang.indent(def, 6)).append(",\n");
    }
    b.append("    ]\n  }\n\n");
    b.append(renderCall(clientVersion));
    b.append("}\n");
    return b.toString();
  }

  private static final String SOURCES =
      String.join(
          "\n",
          "  pub sources(workspace: Workspace!): Directory! {",
          "    directory.withDirectory(",
          "      workspace.cwd,",
          "      workspace.directory(\".\", exclude: [\"**/.git\", \"**/target/**\"], gitignore:"
              + " true),",
          "    )",
          "  }",
          "");

  private static String renderCall(String clientVersion) {
    return String.join(
        "\n",
        "  pub call(",
        "    receiverType: String!,",
        "    receiverValue: JSON,",
        "    fnName: String!,",
        "    fnArgs: JSON!,",
        "    callDigest: String,",
        "  ): JSON! {",
        "    let request = JSON.encode({{",
        "      receiverType: receiverType,",
        "      receiverValue: receiverValue,",
        "      fnName: fnName,",
        "      fnArgs: fnArgs,",
        "    }})",
        "    let build = JavaModuleBuild()",
        "    # A build failure stays out of the rescue below, so it surfaces unchanged.",
        "    let jar = build.jar.sync",
        "    # The engine release the module's core is generated for, which an engine",
        "    # that serves declared releases serves to this process.",
        "    let result = build",
        "      .runtime(jar)",
        "      .withEnvVariable(\"DAGGER_MODULE_CALL_DIGEST\", callDigest ?? \"\")",
        "      .withEnvVariable("
            + Dang.quote(CLIENT_VERSION_VARIABLE)
            + ", "
            + Dang.quote(clientVersion)
            + ")",
        "      .withExec(",
        "        [\"java\", \"-jar\", \"/opt/module/module.jar\", \"engine-call\", \"--output\", "
            + Dang.quote(RESULT_PATH)
            + "],",
        "        stdin: request,",
        "        experimentalPrivilegedNesting: true,",
        "      )",
        "      .file(" + Dang.quote(RESULT_PATH) + ")",
        "      .contents rescue {",
        "        err: GraphQLError => raiseFunctionError(err)",
        "      }",
        "    (result :: JSON!)",
        "  }",
        "",
        "  # The exec error carries the end of the dispatcher's stderr, whose last marker",
        "  # line holds the function's error. Without one, the exec failed before the",
        "  # function returned, and its own error is raised again.",
        "  let raiseFunctionError(err: GraphQLError!): String! {",
        "    let marker = " + Dang.quote(FUNCTION_ERROR_MARKER),
        "    let stderr = ((JSON.decode(err.extensions) :: {{stderr: String}}).stderr ?? \"\")"
            + " rescue \"\"",
        "    let lines = stderr.split(\"\\n\").filter { line => line.hasPrefix(marker) }",
        "    if (lines.isEmpty) {",
        "      raise err",
        "    }",
        "    raise ((JSON.decode(lines.takeLast(1).join(\"\").trimPrefix(marker)) :: String!)"
            + " rescue err.message)",
        "  }",
        "");
  }

  private static String renderObject(ObjectInfo object, String moduleName) {
    StringBuilder b = new StringBuilder("typeDef.withObject(").append(Dang.quote(object.name()));
    appendNamed(b, "description", object.description());
    b.append(")");

    if (object.isCollection()) {
      b.append("\n  .withCollection");
    }
    for (FieldInfo field : object.fields()) {
      if (field.isKeys()) {
        b.append("\n  .withCollectionKeys(").append(Dang.quote(field.name())).append(")");
      }
      if (field.isDelta()) {
        b.append("\n  .withCollectionDelta(").append(Dang.quote(field.name())).append(")");
      }
    }
    for (FunctionInfo function : object.functions()) {
      if (function.isGet()) {
        b.append("\n  .withCollectionGet(").append(Dang.quote(function.name())).append(")");
      }
    }
    for (FunctionInfo function : object.functions()) {
      b.append("\n  .withFunction(\n")
          .append(Dang.indent(renderFunction(object, function), 4))
          .append("\n  )");
    }
    for (FieldInfo field : object.fields()) {
      b.append("\n  .withField(")
          .append(Dang.quote(field.name()))
          .append(", ")
          .append(DaggerType.of(field.type()).toDangTypeDef());
      appendNamed(b, "description", field.description());
      b.append(")");
    }
    if (object.constructor().isPresent()) {
      b.append("\n  .withConstructor(\n")
          .append(Dang.indent(renderFunction(object, object.constructor().get()), 4))
          .append("\n  )");
    } else if (DaggerModuleAnnotationProcessor.areSimilar(object.name(), moduleName)) {
      // The engine finds a module's entry object by its constructor, and the legacy runtime
      // never declared one for an object without constructor arguments.
      b.append("\n  .withConstructor(function(\"\", typeDef.withObject(")
          .append(Dang.quote(object.name()))
          .append(")))");
    }
    return b.toString();
  }

  private static String renderEnum(EnumInfo enumInfo) {
    StringBuilder b = new StringBuilder("typeDef.withEnum(").append(Dang.quote(enumInfo.name()));
    appendNamed(b, "description", enumInfo.description());
    b.append(")");
    for (var value : enumInfo.values()) {
      b.append("\n  .withEnumValue(").append(Dang.quote(value.value()));
      appendNamed(b, "description", value.description());
      b.append(")");
    }
    return b.toString();
  }

  private static String renderFunction(ObjectInfo object, FunctionInfo function) {
    boolean isConstructor = "<init>".equals(function.name());
    String returnType =
        isConstructor
            ? DaggerType.of(object.qualifiedName()).toDangTypeDef()
            : DaggerType.of(function.returnType()).toDangTypeDef();

    StringBuilder b =
        new StringBuilder("function(")
            .append(Dang.quote(isConstructor ? "" : function.name()))
            .append(", ")
            .append(returnType)
            .append(")");
    if (isNotBlank(function.description())) {
      b.append("\n  .withDescription(").append(Dang.quote(function.description())).append(")");
    }
    switch (function.cache()) {
      case "" -> {}
      case "never" -> b.append("\n  .withCachePolicy(FunctionCachePolicy.Never)");
      case "session" -> b.append("\n  .withCachePolicy(FunctionCachePolicy.PerSession)");
      default ->
          b.append("\n  .withCachePolicy(FunctionCachePolicy.Default, timeToLive: ")
              .append(Dang.quote(function.cache()))
              .append(")");
    }
    if (function.isCheck()) {
      b.append("\n  .withCheck");
    }
    if (function.isGenerate()) {
      b.append("\n  .withGenerator");
    }
    if (function.isUp()) {
      b.append("\n  .withUp");
    }
    for (ParameterInfo parameter : function.parameters()) {
      b.append("\n  .withArg(")
          .append(Dang.quote(parameter.name()))
          .append(", ")
          .append(DaggerType.of(parameter.type()).toDangTypeDef());
      // The processor strips Optional<...> from an argument's type and records it here instead.
      if (parameter.optional()) {
        b.append(".withOptional(true)");
      }
      appendNamed(b, "description", parameter.description());
      if (parameter.defaultValue().isPresent()) {
        b.append(", defaultValue: (")
            .append(Dang.quote(parameter.defaultValue().get()))
            .append(" :: Dagger.JSON!)");
      }
      appendNamed(b, "defaultPath", parameter.defaultPath().orElse(null));
      if (parameter.ignore().isPresent()) {
        b.append(", ignore: [");
        String[] ignore = parameter.ignore().get();
        for (int i = 0; i < ignore.length; i++) {
          b.append(i == 0 ? "" : ", ").append(Dang.quote(ignore[i]));
        }
        b.append("]");
      }
      b.append(")");
    }
    return b.toString();
  }

  private static void appendNamed(StringBuilder b, String name, String value) {
    if (isNotBlank(value)) {
      b.append(", ").append(name).append(": ").append(Dang.quote(value));
    }
  }

  private static boolean isNotBlank(String value) {
    return value != null && !value.isBlank();
  }
}
