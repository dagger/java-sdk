package io.dagger.annotation.processor;

import static org.assertj.core.api.Assertions.assertThat;

import io.dagger.module.info.EnumInfo;
import io.dagger.module.info.EnumValueInfo;
import io.dagger.module.info.FieldInfo;
import io.dagger.module.info.FunctionInfo;
import io.dagger.module.info.ModuleInfo;
import io.dagger.module.info.ObjectInfo;
import io.dagger.module.info.ParameterInfo;
import io.dagger.module.info.TypeInfo;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import javax.lang.model.type.TypeKind;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;

class DangEntrypointRendererTest {

  private static final String ENUM_QNAME = "io.dagger.modules.demo.Severity";

  @AfterEach
  void resetKnownEnums() {
    DaggerType.setKnownEnums(Set.of());
  }

  @Test
  void theFileStartsWithTheOwnershipHeader() {
    assertThat(DangEntrypointRenderer.render(module(), "demo"))
        .startsWith("# This file has been generated by dagger-java-sdk. DO NOT EDIT.\n");
  }

  /** Pinned whole: nothing parses this output before the engine loads the module. */
  @Test
  void typesDescribesEveryObjectAndEnumWithoutAWorkspace() {
    assertThat(DangEntrypointRenderer.render(module(), "demo"))
        .contains(
            String.join(
                "\n",
                "  pub types: [TypeDef!]! {",
                "    [",
                "      typeDef.withObject(\"Demo\", description: \"A demo module\")",
                "        .withFunction(",
                "          function(\"greet\", typeDef.withKind(TypeDefKind.STRING_KIND))",
                "            .withDescription(\"Say hello\")",
                "            .withArg(\"name\", typeDef.withKind(TypeDefKind.STRING_KIND),"
                    + " description: \"who to greet\")",
                "            .withArg(\"loud\","
                    + " typeDef.withKind(TypeDefKind.BOOLEAN_KIND).withOptional(true))",
                "            .withArg(\"level\", typeDef.withEnum(\"Severity\"))",
                "            .withArg(\"src\", typeDef.withObject(\"Directory\"), defaultPath:"
                    + " \".\", ignore: [\"target\", \"*.log\"])",
                "        )",
                "        .withFunction(",
                "          function(\"lint\","
                    + " typeDef.withKind(TypeDefKind.VOID_KIND).withOptional(true))",
                "            .withCachePolicy(FunctionCachePolicy.Never)",
                "            .withCheck",
                "        )",
                "        .withField(\"source\", typeDef.withObject(\"Directory\"), description:"
                    + " \"the source tree\")",
                "        .withConstructor(",
                "          function(\"\", typeDef.withObject(\"Demo\"))",
                "            .withArg(\"prefix\", typeDef.withKind(TypeDefKind.STRING_KIND),"
                    + " defaultValue: (\"\\\"Hi\\\"\" :: Dagger.JSON!))",
                "        ),",
                "      typeDef.withEnum(\"Severity\")",
                "        .withEnumValue(\"HIGH\", description: \"very bad\")",
                "        .withEnumValue(\"MixedCase\"),",
                "    ]",
                "  }"));
  }

  @Test
  void cachePoliciesFollowTheValuesEveryOtherSdkAccepts() {
    assertThat(renderFunction("never")).contains(".withCachePolicy(FunctionCachePolicy.Never)");
    assertThat(renderFunction("session"))
        .contains(".withCachePolicy(FunctionCachePolicy.PerSession)");
    assertThat(renderFunction("10s"))
        .contains(".withCachePolicy(FunctionCachePolicy.Default, timeToLive: \"10s\")");
    assertThat(renderFunction("")).doesNotContain("withCachePolicy");
  }

  /**
   * The engine finds the entry object by its constructor, so the object named after the module gets
   * one even when its Java class has no constructor arguments; no other object does.
   */
  @Test
  void theEntryObjectWithoutConstructorArgumentsStillDeclaresAConstructor() {
    ObjectInfo entry = object("Hello", Optional.empty());
    ObjectInfo other = object("Item", Optional.empty());

    String dang =
        DangEntrypointRenderer.render(
            new ModuleInfo(null, new ObjectInfo[] {entry, other}, Map.of()), "hello");

    assertThat(dang).contains(".withConstructor(function(\"\", typeDef.withObject(\"Hello\")))");
    assertThat(dang.split("\\.withConstructor\\(", -1)).hasSize(2);
  }

  @Test
  void sourcesReturnsTheModuleDirectoryAtItsWorkspacePath() {
    assertThat(DangEntrypointRenderer.render(module(), "demo"))
        .contains(
            String.join(
                "\n",
                "  pub sources(workspace: Workspace!): Directory! {",
                "    directory.withDirectory(",
                "      workspace.cwd,",
                "      workspace.directory(\".\", exclude: [\"**/.git\", \"**/target/**\"],"
                    + " gitignore: true),",
                "    )",
                "  }"));
  }

  @Test
  void callRunsTheJarInEngineCallModeKeyedOnTheCallDigest() {
    assertThat(DangEntrypointRenderer.render(module(), "demo"))
        .contains(
            String.join(
                "\n",
                "  pub call(",
                "    receiverType: String!,",
                "    receiverValue: JSON,",
                "    fnName: String!,",
                "    fnArgs: JSON!,",
                "    callDigest: String,",
                "  ): JSON! {"))
        .contains(".withEnvVariable(\"DAGGER_MODULE_CALL_DIGEST\", callDigest ?? \"\")")
        .contains(
            "[\"java\", \"-jar\", \"/opt/module/module.jar\", \"engine-call\", \"--output\","
                + " \"/dagger/result.json\"],")
        .contains("stdin: request,")
        .contains("experimentalPrivilegedNesting: true,")
        .contains(".file(\"/dagger/result.json\")")
        .contains("(result :: JSON!)");
  }

  @Test
  void aFailedCallRaisesTheTextAfterTheLastErrorMarker() {
    assertThat(DangEntrypointRenderer.render(module(), "demo"))
        .contains("let jar = build.jar.sync")
        .contains(".contents rescue {\n        err: GraphQLError => raiseFunctionError(err)\n")
        .contains("let marker = \"::dagger-function-error::\"")
        .contains("lines.takeLast(1)");
  }

  @Test
  void descriptionsAreEscapedSoTheOutputStaysParseable() {
    ObjectInfo object =
        new ObjectInfo(
            "Demo",
            "io.dagger.modules.demo.Demo",
            "a \"quoted\" \\ description\nover two lines",
            new FieldInfo[0],
            new FunctionInfo[0],
            Optional.empty());

    String dang =
        DangEntrypointRenderer.render(
            new ModuleInfo(null, new ObjectInfo[] {object}, Map.of()), "demo");

    assertThat(dang)
        .contains(
            "typeDef.withObject(\"Demo\", description:"
                + " \"a \\\"quoted\\\" \\\\ description\\nover two lines\")");
  }

  private static String renderFunction(String cache) {
    FunctionInfo fn =
        new FunctionInfo(
            "fresh", "fresh", "", cache, string(), new ParameterInfo[0], false, false, false);
    ObjectInfo object =
        new ObjectInfo(
            "Demo",
            "io.dagger.modules.demo.Demo",
            "",
            new FieldInfo[0],
            new FunctionInfo[] {fn},
            Optional.empty());
    return DangEntrypointRenderer.render(
        new ModuleInfo(null, new ObjectInfo[] {object}, Map.of()), "demo");
  }

  private static ObjectInfo object(String name, Optional<FunctionInfo> constructor) {
    return new ObjectInfo(
        name,
        "io.dagger.modules.hello." + name,
        "",
        new FieldInfo[0],
        new FunctionInfo[0],
        constructor);
  }

  private static TypeInfo string() {
    return new TypeInfo("java.lang.String", TypeKind.DECLARED.name());
  }

  private static ParameterInfo parameter(String name, TypeInfo type) {
    return new ParameterInfo(
        name, "", type, false, Optional.empty(), Optional.empty(), Optional.empty());
  }

  private static ModuleInfo module() {
    FunctionInfo greet =
        new FunctionInfo(
            "greet",
            "greet",
            "Say hello",
            "",
            string(),
            new ParameterInfo[] {
              new ParameterInfo(
                  "name",
                  "who to greet",
                  string(),
                  false,
                  Optional.empty(),
                  Optional.empty(),
                  Optional.empty()),
              new ParameterInfo(
                  "loud",
                  "",
                  new TypeInfo("boolean", TypeKind.BOOLEAN.name()),
                  true,
                  Optional.empty(),
                  Optional.empty(),
                  Optional.empty()),
              parameter("level", new TypeInfo(ENUM_QNAME, TypeKind.DECLARED.name())),
              new ParameterInfo(
                  "src",
                  "",
                  new TypeInfo("io.dagger.client.modules.core.Directory", TypeKind.DECLARED.name()),
                  false,
                  Optional.empty(),
                  Optional.of("."),
                  Optional.of(new String[] {"target", "*.log"})),
            },
            false,
            false,
            false);

    FunctionInfo lint =
        new FunctionInfo(
            "lint",
            "lint",
            "",
            "never",
            new TypeInfo("void", TypeKind.VOID.name()),
            new ParameterInfo[0],
            true,
            false,
            false);

    FunctionInfo constructor =
        new FunctionInfo(
            "<init>",
            "<init>",
            "",
            "",
            new TypeInfo("io.dagger.modules.demo.Demo", TypeKind.DECLARED.name()),
            new ParameterInfo[] {
              new ParameterInfo(
                  "prefix",
                  "",
                  string(),
                  false,
                  Optional.of("\"Hi\""),
                  Optional.empty(),
                  Optional.empty()),
            },
            false,
            false,
            false);

    ObjectInfo demo =
        new ObjectInfo(
            "Demo",
            "io.dagger.modules.demo.Demo",
            "A demo module",
            new FieldInfo[] {
              new FieldInfo(
                  "source",
                  "the source tree",
                  new TypeInfo("io.dagger.client.modules.core.Directory", TypeKind.DECLARED.name()))
            },
            new FunctionInfo[] {greet, lint},
            Optional.of(constructor));

    EnumInfo severity =
        new EnumInfo(
            "Severity",
            "",
            new EnumValueInfo[] {
              new EnumValueInfo("HIGH", "very bad"), new EnumValueInfo("MixedCase", "")
            });

    return new ModuleInfo("A demo module", new ObjectInfo[] {demo}, Map.of(ENUM_QNAME, severity));
  }
}
